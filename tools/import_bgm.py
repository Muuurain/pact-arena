"""
Import and master external BGM tracks (e.g. generated by Doubao AI) into Godot-ready
seamless looping 44.1 kHz stereo OGG files for Pact Arena (血契竞技场).

Pipeline per track (spec: docs/bgm_arena_soundtrack_loop_set_v01_prompt.md §10/§11):
  1. Decode source (wav/mp3/flac/m4a/aac/ogg) -> 44.1 kHz stereo float samples.
  2. Trim leading/trailing silence (-45 dBFS gate, 30 ms pad).
  3. 1.6 s equal-power tail-to-head crossfade for a zero-click seamless loop.
  4. EBU R128 loudness normalization to -15.5 LUFS, true peak <= -1.0 dBTP.
  5. Archive a 16-bit PCM 44.1 kHz stereo WAV master under raw_audio/.
  6. Encode two 160 kbps Vorbis copies into assets/audio/bgm/:
       - spec v01 long name: bgm_arena_soundtrack_loop_<variant>_v01.ogg
       - engine legacy alias: bgm_<variant>.ogg
  7. EBU R128 re-measurement printed as an acceptance report.

Usage:
    Place either spec-compliant v01 names OR short track names inside
    D:\\Code\\project\\pact_arena\\raw_audio\\:
      - bgm_arena_soundtrack_loop_sanctuary_v01.(wav|mp3|...) or bgm_sanctuary.*
      - bgm_arena_soundtrack_loop_combat_v01.(wav|mp3|...)    or bgm_combat.*
      - bgm_arena_soundtrack_loop_boss_v01.(wav|mp3|...)      or bgm_boss.*
    Then run:
        python tools/import_bgm.py
"""
import argparse
import json
import math
import re
import subprocess
import tempfile
import wave
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
RAW_DIR = ROOT / "raw_audio"
OUT_DIR = ROOT / "assets" / "audio" / "bgm"
FFMPEG = Path(
    r"D:\ffmpeg\ffmpeg-2025-02-26-git-99e2af4e78-full_build"
    r"\ffmpeg-2025-02-26-git-99e2af4e78-full_build\bin\ffmpeg.exe"
)
FFPROBE = FFMPEG.parent / "ffprobe.exe"

SR = 44100
TARGET_LUFS = -15.5
TARGET_TP_DBTP = -1.0
OGG_BITRATE = "160k"
TARGET_DURATION_S = 90.0
DURATION_TOLERANCE_S = 2.0
SILENCE_GATE_DBFS = -45.0
DEEP_SILENCE_DBFS = -60.0
FADE_IN_S = 0.02
SUPPORTED_EXTS = (".wav", ".mp3", ".flac", ".m4a", ".aac", ".ogg")

# (legacy_track_id, v01_spec_stem, legacy_stem)
TRACK_SPECS = [
    ("bgm_sanctuary", "bgm_arena_soundtrack_loop_sanctuary_v01", "bgm_sanctuary"),
    ("bgm_combat", "bgm_arena_soundtrack_loop_combat_v01", "bgm_combat"),
    ("bgm_boss", "bgm_arena_soundtrack_loop_boss_v01", "bgm_boss"),
]


def find_source(stems: tuple[str, ...]) -> Path | None:
    for stem in stems:
        for ext in SUPPORTED_EXTS:
            cand = RAW_DIR / f"{stem}{ext}"
            if cand.exists():
                return cand
    return None


def decode_to_stereo_float(src: Path) -> np.ndarray:
    """Decode any supported container to 44.1 kHz stereo float64 samples."""
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as tf:
        tmp_wav = Path(tf.name)
    try:
        cmd = [
            str(FFMPEG), "-y", "-loglevel", "error",
            "-i", str(src),
            "-ar", str(SR), "-ac", "2", "-sample_fmt", "s16",
            str(tmp_wav),
        ]
        subprocess.run(cmd, check=True)
        with wave.open(str(tmp_wav), "rb") as wf:
            frames = wf.readframes(wf.getnframes())
        data = np.frombuffer(frames, dtype=np.int16).reshape(-1, 2).astype(np.float64) / 32768.0
        return data
    finally:
        if tmp_wav.exists():
            tmp_wav.unlink()


def trim_silence(audio: np.ndarray, gate_dbfs: float = SILENCE_GATE_DBFS) -> np.ndarray:
    """Remove leading/trailing silence below the gate, keeping a short pad."""
    gate_lin = 10.0 ** (gate_dbfs / 20.0)
    mag = np.max(np.abs(audio), axis=1)
    idx = np.where(mag > gate_lin)[0]
    if len(idx) == 0:
        return audio
    pad = int(0.06 * SR)
    start = max(0, int(idx[0]) - pad)
    end = min(len(audio), int(idx[-1]) + pad)
    return audio[start:end]


def trim_deep_silence(audio: np.ndarray, gate_dbfs: float = DEEP_SILENCE_DBFS,
                      pad_s: float = 0.01) -> np.ndarray:
    """Second-pass trim at -60 dBFS so no sub-threshold decay tail or encoder
    padding survives past the 0.05 s head/tail silence limit (spec §12)."""
    gate_lin = 10.0 ** (gate_dbfs / 20.0)
    mag = np.max(np.abs(audio), axis=1)
    idx = np.where(mag > gate_lin)[0]
    if len(idx) == 0:
        return audio
    pad = int(pad_s * SR)
    start = max(0, int(idx[0]) - pad)
    end = min(len(audio), int(idx[-1]) + pad)
    return audio[start:end]


def apply_fade_in(audio: np.ndarray, fade_s: float = FADE_IN_S) -> np.ndarray:
    """20 ms linear fade-in ramp to prevent a zero-sample onset click (spec §10)."""
    n = min(int(fade_s * SR), len(audio) // 6)
    if n < 2:
        return audio
    ramp = np.linspace(0.0, 1.0, n)[:, None]
    out = audio.copy()
    out[:n] *= ramp
    return out


def make_seamless_loop(audio: np.ndarray, xfade_s: float = 1.6) -> np.ndarray:
    """Equal-power crossfade the tail into the head, preserving full length.

    The opening fade window blends the original head with the tail (cosine
    tail ramp), so the file end wraps back to the smoothed opening without a
    click; the remaining samples stay intact to preserve the target duration.
    """
    fade_n = min(int(xfade_s * SR), len(audio) // 5)
    if fade_n < 100:
        return audio
    head = audio[:fade_n]
    tail = audio[-fade_n:]
    t = np.linspace(0.0, math.pi * 0.5, fade_n)[:, None]
    out = audio.copy()
    out[:fade_n] = head * np.sin(t) + tail * np.cos(t)
    return out


def write_wav(audio: np.ndarray, dest: Path) -> None:
    pcm = (np.clip(audio, -1.0, 1.0) * 32767.0).astype(np.int16)
    dest.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(dest), "wb") as wf:
        wf.setnchannels(2)
        wf.setsampwidth(2)
        wf.setframerate(SR)
        wf.writeframes(pcm.tobytes())


def measure_loudnorm_params(src_wav: Path) -> dict:
    """First-pass loudness measurement for two-pass EBU R128 normalization."""
    cmd = [
        str(FFMPEG), "-hide_banner", "-i", str(src_wav),
        "-af", f"loudnorm=I={TARGET_LUFS}:TP={TARGET_TP_DBTP}:LRA=11:print_format=json",
        "-f", "null", "-",
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True, check=True)
    match = re.search(r"\{.*\}", proc.stderr, re.S)
    if not match:
        return {}
    return json.loads(match.group(0))


def loudnorm_master(src_wav: Path, dest_wav: Path) -> None:
    """Two-pass EBU R128 normalize to -15.5 LUFS, true peak <= -1.0 dBTP."""
    dest_wav.parent.mkdir(parents=True, exist_ok=True)
    params = measure_loudnorm_params(src_wav)
    af = f"loudnorm=I={TARGET_LUFS}:TP={TARGET_TP_DBTP}:LRA=11"
    if params:
        af += (
            f":measured_I={params['input_i']}"
            f":measured_LRA={params['input_lra']}"
            f":measured_TP={params['input_tp']}"
            f":measured_thresh={params['input_thresh']}"
            f":offset={params['target_offset']}:linear=true"
        )
    af += ":print_format=summary"
    cmd = [
        str(FFMPEG), "-y", "-loglevel", "error",
        "-i", str(src_wav),
        "-af", af,
        "-ar", str(SR), "-ac", "2", "-sample_fmt", "s16",
        str(dest_wav),
    ]
    subprocess.run(cmd, check=True)


def encode_ogg(wav_src: Path, dest: Path, bitrate: str = OGG_BITRATE) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    cmd = [
        str(FFMPEG), "-y", "-loglevel", "error",
        "-i", str(wav_src),
        "-c:a", "libvorbis", "-b:a", bitrate,
        "-minrate", bitrate, "-maxrate", bitrate,
        str(dest),
    ]
    subprocess.run(cmd, check=True)


def head_tail_silence_ms(audio: np.ndarray, gate_dbfs: float = DEEP_SILENCE_DBFS) -> tuple[float, float]:
    """Head/tail silence duration in milliseconds below -60 dBFS."""
    gate_lin = 10.0 ** (gate_dbfs / 20.0)
    mag = np.max(np.abs(audio), axis=1)
    idx = np.where(mag > gate_lin)[0]
    if len(idx) == 0:
        return len(audio) / SR * 1000.0, len(audio) / SR * 1000.0
    head = idx[0] / SR * 1000.0
    tail = (len(audio) - idx[-1] - 1) / SR * 1000.0
    return head, tail


def probe_duration(path: Path) -> float:
    out = subprocess.run(
        [str(FFPROBE), "-v", "error", "-show_entries", "format=duration",
         "-of", "default=noprint_wrappers=1:nokey=1", str(path)],
        capture_output=True, text=True, check=True,
    )
    return float(out.stdout.strip())


def measure_r128(path: Path) -> dict:
    """Re-measure integrated loudness and true peak with the EBU R128 scanner.

    Only the final Summary block is parsed; the rolling per-frame lines report
    a -70 LUFS noise floor early in the track and must not be mistaken for the
    integrated loudness.
    """
    proc = subprocess.run(
        [str(FFMPEG), "-hide_banner", "-i", str(path),
         "-af", "ebur128=peak=true", "-f", "null", "-"],
        capture_output=True, text=True,
    )
    text = proc.stderr
    summary = text[text.find("Summary"):] if "Summary" in text else text
    i_match = re.search(r"I:\s*(-?[\d.]+)\s*LUFS", summary)
    tp_match = re.search(r"Peak:\s*(-?[\d.]+)\s*dB(?:TP|FS)", summary)
    return {
        "lufs": float(i_match.group(1)) if i_match else float("nan"),
        "tp_dbtp": float(tp_match.group(1)) if tp_match else float("nan"),
    }


def valid_asset_name(stem: str) -> bool:
    return bool(re.fullmatch(r"[a-z0-9_]+", stem))


def process_track(legacy_id: str, v01_stem: str, legacy_stem: str, xfade_s: float) -> dict | None:
    src = find_source((v01_stem, legacy_stem))
    if src is None:
        print(f"[SKIP] {legacy_id}: place {v01_stem}.* or {legacy_id}.* in {RAW_DIR}")
        return None

    print(f"[IMPORT] {src.name} -> {legacy_id} ...")
    raw = decode_to_stereo_float(src)
    trimmed = trim_deep_silence(trim_silence(raw))
    looped = apply_fade_in(make_seamless_loop(trimmed, xfade_s=xfade_s))

    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as tf:
        pre_wav = Path(tf.name)
    try:
        write_wav(looped, pre_wav)
        # Archive the normalized 44.1 kHz 16-bit PCM master under raw_audio/.
        master_wav = RAW_DIR / f"{v01_stem}.wav"
        loudnorm_master(pre_wav, master_wav)

        OUT_DIR.mkdir(parents=True, exist_ok=True)
        ogg_v01 = OUT_DIR / f"{v01_stem}.ogg"
        ogg_legacy = OUT_DIR / f"{legacy_id}.ogg"
        encode_ogg(master_wav, ogg_v01)
        encode_ogg(master_wav, ogg_legacy)

        duration = probe_duration(master_wav)
        r128 = measure_r128(master_wav)
        master_audio = decode_to_stereo_float(master_wav)
        head_ms, tail_ms = head_tail_silence_ms(master_audio)
        ogg_kbps = ogg_legacy.stat().st_size * 8.0 / duration / 1000.0
        report = {
            "legacy_id": legacy_id,
            "v01_stem": v01_stem,
            "master_wav": master_wav,
            "ogg_v01": ogg_v01,
            "ogg_legacy": ogg_legacy,
            "duration_s": duration,
            "lufs": r128["lufs"],
            "tp_dbtp": r128["tp_dbtp"],
            "head_sil_ms": head_ms,
            "tail_sil_ms": tail_ms,
            "ogg_kbps": ogg_kbps,
            "master_bytes": master_wav.stat().st_size,
            "ogg_bytes": ogg_legacy.stat().st_size,
        }
        print(
            f"[OK] {legacy_id}: {duration:.2f}s, {r128['lufs']:.1f} LUFS, "
            f"TP {r128['tp_dbtp']:.2f} dBTP, tail {tail_ms:.0f} ms sil, "
            f"{ogg_kbps:.0f} kbps, {report['ogg_bytes']} bytes"
        )
        return report
    finally:
        if pre_wav.exists():
            pre_wav.unlink()


def print_acceptance(reports: list[dict]) -> None:
    print("\n=== BGM acceptance report ===")
    failures: list[str] = []
    lufs_values: list[float] = []
    for r in reports:
        ok_duration = abs(r["duration_s"] - TARGET_DURATION_S) <= DURATION_TOLERANCE_S
        ok_tp = r["tp_dbtp"] <= TARGET_TP_DBTP + 0.05
        ok_name = valid_asset_name(r["v01_stem"]) and valid_asset_name(r["legacy_id"])
        ok_files = r["master_wav"].exists() and r["ogg_v01"].exists() and r["ogg_legacy"].exists()
        ok_silence = r["head_sil_ms"] <= 50.0 and r["tail_sil_ms"] <= 50.0
        lufs_values.append(r["lufs"])
        flags = []
        if not ok_duration:
            flags.append("duration out of ±2s")
            failures.append(f"{r['legacy_id']}: duration {r['duration_s']:.2f}s")
        if not ok_tp:
            flags.append("true peak exceeds -1.0 dBTP")
            failures.append(f"{r['legacy_id']}: TP {r['tp_dbtp']:.2f} dBTP")
        if not ok_name:
            flags.append("invalid asset name")
            failures.append(f"{r['legacy_id']}: name charset")
        if not ok_files:
            flags.append("missing output file")
            failures.append(f"{r['legacy_id']}: missing output")
        if not ok_silence:
            flags.append("head/tail silence > 50 ms")
            failures.append(f"{r['legacy_id']}: head {r['head_sil_ms']:.0f} ms / tail {r['tail_sil_ms']:.0f} ms")
        status = "PASS" if not flags else "WARN: " + "; ".join(flags)
        print(
            f"  {r['legacy_id']:<16} {r['duration_s']:6.2f}s  {r['lufs']:6.1f} LUFS  "
            f"TP {r['tp_dbtp']:6.2f} dBTP  tail {r['tail_sil_ms']:4.0f} ms  "
            f"{r['ogg_kbps']:.0f} kbps  [{status}]"
        )

    if len(lufs_values) >= 2:
        spread = max(lufs_values) - min(lufs_values)
        print(f"\n  Inter-track loudness spread: {spread:.2f} LU (limit <= 1.5 LU)")
        if spread > 1.5:
            failures.append(f"loudness spread {spread:.2f} LU > 1.5 LU")

    if failures:
        print("\n=== Acceptance warnings ===")
        for f in failures:
            print(f"  ! {f}")
    else:
        print("\n=== All BGM acceptance checks passed ===")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Import and loop-master Doubao BGM files into Pact Arena.")
    parser.add_argument("--xfade", type=float, default=1.6, help="Crossfade seconds for seamless loop (default 1.6s).")
    args = parser.parse_args()

    RAW_DIR.mkdir(parents=True, exist_ok=True)
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    reports: list[dict] = []
    for legacy_id, v01_stem, legacy_stem in TRACK_SPECS:
        rep = process_track(legacy_id, v01_stem, legacy_stem, args.xfade)
        if rep is not None:
            reports.append(rep)

    if reports:
        print_acceptance(reports)
    else:
        print(f"Place spec v01 or bgm_sanctuary / bgm_combat / bgm_boss audio files in {RAW_DIR} and re-run.")
